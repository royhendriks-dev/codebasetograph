import type { Graph } from "./model.js";
import { isTestPath } from "./query.js";

/**
 * Folder-level summary that is safe to show outside the repository: only top-level folder names and counts. No file,
 * symbol, route, table, config-key or Kubernetes object names, unlike `graph.json` and the HTML views.
 */
export interface Overview {
  version: 1;
  root: string;
  totals: { files: number; symbols: number; links: number };
  groups: Array<{ id: string; files: number; testFiles: number; symbols: number; languages: Record<string, number>; externalImports: number }>;
  /** References between files of two different groups (imports, references, extends); `from` refers to `to`. */
  links: Array<{ from: string; to: string; count: number }>;
}

/** Files directly in the root share one group, so their names do not appear. */
export const ROOT_GROUP = "(root)";
const groupOf = (p: string) => (p.includes("/") ? p.slice(0, p.indexOf("/")) : ROOT_GROUP);
const byCodeUnit = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

export function overview(g: Graph): Overview {
  const groups = new Map<string, Overview["groups"][number]>();
  const group = (p: string) => {
    const id = groupOf(p);
    return groups.get(id) ?? groups.set(id, { id, files: 0, testFiles: 0, symbols: 0, languages: {}, externalImports: 0 }).get(id)!;
  };
  for (const f of Object.values(g.files)) {
    const gr = group(f.path);
    gr.files++;
    if (isTestPath(f.path)) gr.testFiles++;
    gr.symbols += f.symbols.length;
    const lang = f.lang ?? "ts";
    gr.languages[lang] = (gr.languages[lang] ?? 0) + 1;
  }
  const links = new Map<string, number>();
  for (const e of g.edges) {
    if (e.kind === "declares" || !e.from.startsWith("file:")) continue;
    const from = e.from.slice(5);
    if (!(from in g.files)) continue;
    if (e.to.startsWith("pkg:")) { group(from).externalImports++; continue; }
    const to = e.to.slice(5);
    if (!e.to.startsWith("file:") || !(to in g.files)) continue;
    const a = groupOf(from), b = groupOf(to);
    if (a !== b) links.set(`${a}\u0000${b}`, (links.get(`${a}\u0000${b}`) ?? 0) + 1);
  }
  const sorted = [...groups.values()].sort((a, b) => byCodeUnit(a.id, b.id));
  for (const gr of sorted) gr.languages = Object.fromEntries(Object.entries(gr.languages).sort((a, b) => byCodeUnit(a[0], b[0])));
  return {
    version: 1,
    root: g.root,
    totals: { files: Object.keys(g.files).length, symbols: g.nodes.filter((n) => n.kind === "symbol").length, links: g.edges.filter((e) => e.kind !== "declares").length },
    groups: sorted,
    links: [...links].map(([k, count]) => { const [from, to] = k.split("\u0000"); return { from, to, count }; })
      .sort((a, b) => byCodeUnit(a.from, b.from) || byCodeUnit(a.to, b.to)),
  };
}

/** Folder names are repository text: keep them inside a quoted Mermaid label without quotes, brackets or markup. */
const label = (s: string) => s.replace(/["<>[\]{}|#`]/g, "_");

/** Markdown page with a Mermaid diagram (GitHub draws it) and a table of the same numbers, for reading in the repository. */
export function renderOverviewMarkdown(o: Overview): string {
  const id = new Map(o.groups.map((gr, i) => [gr.id, `g${i}`]));
  const nodes = o.groups.map((gr) => `  ${id.get(gr.id)}["${label(gr.id)}<br/>${gr.files} files, ${gr.symbols} symbols"]`);
  const edges = o.links.map((l) => `  ${id.get(l.from)} -->|${l.count}| ${id.get(l.to)}`);
  const rows = o.groups.map((gr) => `| ${label(gr.id)} | ${gr.files} | ${gr.testFiles} | ${gr.symbols} | ${Object.entries(gr.languages).map(([k, v]) => `${k} ${v}`).join(", ")} | ${gr.externalImports} |`);
  return [
    `# Code graph: ${label(o.root)}`,
    "",
    `Generated by \`cbtg view --overview\` from \`.cbtg/graph.json\`: ${o.totals.files} files, ${o.totals.symbols} symbols, ${o.totals.links} links. One box per top-level folder; an arrow means files in one folder refer to files in the other (imports, references, extends), with the number of references. Do not edit by hand.`,
    "",
    "```mermaid",
    "flowchart LR",
    ...nodes,
    ...edges,
    "```",
    "",
    "| folder | files | test files | symbols | languages | external imports |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}
